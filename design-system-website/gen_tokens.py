"""Generates the site's tokens.css (Light/Dark/system + responsive) and a compact token dataset for the Tokens pages.
Sources: design-system/tokens/tokens.json (Figma: 772 variables, 4 tiers) and design-system/tokens/code-tokens.json (code names used by the components)."""
import json, re, os, shutil
ROOT = os.path.dirname(os.path.abspath(__file__))
FIG = json.load(open(os.path.join(ROOT, 'design-system/tokens/tokens.json')))
CLOUD = json.load(open(os.path.join(ROOT, 'design-system/tokens/code-tokens.json')))
C = FIG['collections']
def dash(n): return '--' + n.replace('/', '-')
def unit(v, typ, name):
    if typ == 'number' and isinstance(v, (int, float)):
        if 'weight' in name or name.startswith('grid/count') or name.endswith('columns') or 'opacity' in name: return str(v)
        if 'duration' in name: return f'{v}ms'
        return f'{v}px'
    if typ == 'string' and 'family' in name: return f'"{v}", "Inter", system-ui, sans-serif'
    return str(v)
prim = C['Primitives']['variables']
lines_root, lines_dark, lines_tab, lines_mob = [], [], [], []
for n, v in prim.items():
    lines_root.append(f'{dash(n)}: {unit(v["values"]["Value"], v["type"], n)};')
sem = C['Semantic']['variables']
for n, v in sem.items():
    for mode, out in (('Light', lines_root), ('Dark', lines_dark)):
        val = v['values'][mode]
        out.append(f'{dash(n)}: var({dash(val)});' if isinstance(val, str) and val in prim else f'{dash(n)}: {unit(val, v["type"], n)};')
resp = C['Responsive']['variables']
for n, v in resp.items():
    for mode, out in (('Desktop', lines_root), ('Tablet', lines_tab), ('Mobile', lines_mob)):
        val = v['values'][mode]
        r = f'var({dash(val)})' if isinstance(val, str) and val in prim else unit(v['resolved'][mode], v['type'], n)
        if mode == 'Desktop' or val != v['values']['Desktop']: out.append(f'{dash(n)}: {r};')
comp = C['Component']['variables']
for n, v in comp.items():
    lines_root.append(f'{dash(n)}: var({dash(v["alias"])});')
# Cloud (bundle) names
cl_root, cl_dark = [], []
def cref(x):
    m = re.fullmatch(r'\{(.+)\}', x) if isinstance(x, str) else None
    return f'var(--{m.group(1)})' if m else x
for t in CLOUD['color']['tokens']:
    val = t['value']
    if isinstance(val, dict): cl_root.append(f'--{t["name"]}: {cref(val["light"])};'); cl_dark.append(f'--{t["name"]}: {cref(val["dark"])};')
    else: cl_root.append(f'--{t["name"]}: {val};')
for k in ['spacing', 'radius', 'shadow', 'size', 'borderWidth']:
    for t in CLOUD[k]['tokens']:
        val = t['value']
        if isinstance(val, dict): cl_root.append(f'--{t["name"]}: {cref(val["light"])};'); cl_dark.append(f'--{t["name"]}: {cref(val["dark"])};')
        else: cl_root.append(f'--{t["name"]}: {val};')
cl_root.append(f'--font-display: {CLOUD["type"]["families"]["display"]};')
# type style custom props from cloud groups
for g in CLOUD['type']['groups']:
    for s in g['styles']:
        cl_root.append(f'--type-{s["name"]}: {s["fontWeight"]} {s["fontSize"]}/{s["lineHeight"]} var(--font-display);')
faces = '\n'.join(f'@font-face {{ font-family: "Inter Display"; src: url("{f["file"]}") format("truetype"); font-weight: {f["weight"]}; font-style: normal; font-display: swap; }}' for f in CLOUD['type']['fonts'])
ind = lambda L: '\n  '.join(L)
css = f'''/* Marketplace Design System tokens, generated by gen_tokens.py. Code names (bundle.css) + Figma code-syntax names (--color-*) + component tier. */
{faces}
:root {{
  color-scheme: light;
  {ind(cl_root)}
  {ind(lines_root)}
}}
@media (prefers-color-scheme: dark) {{ :root:not([data-theme="light"]) {{
  color-scheme: dark;
  {ind(cl_dark)}
  {ind(lines_dark)}
}} }}
:root[data-theme="dark"] {{
  color-scheme: dark;
  {ind(cl_dark)}
  {ind(lines_dark)}
}}
@media (max-width: 1023px) {{ :root {{
  {ind(lines_tab)}
}} }}
@media (max-width: 639px) {{ :root {{
  {ind(lines_mob)}
}} }}
'''
os.makedirs(os.path.join(ROOT, 'out/fonts'), exist_ok=True)
open(os.path.join(ROOT, 'out/tokens.css'), 'w').write(css)
# Dataset for the docs pages
cloud_names = {}
for t in CLOUD['color']['tokens']: cloud_names[t['name']] = t
for k in ['spacing', 'radius', 'shadow', 'size', 'borderWidth']:
    for t in CLOUD[k]['tokens']: cloud_names[t['name']] = t
def code_name(n):
    cand = n.replace('color/', '', 1).replace('/', '-') if n.startswith('color/') else n.replace('/', '-')
    alts = [cand, cand.replace('elevation-', 'elevation-'), re.sub(r'^effect-', '', cand), re.sub(r'^shadow-', 'elevation-', cand)]
    for a in alts:
        if a in cloud_names: return a
    return None
data = {'primitives': [], 'semantic': [], 'responsive': [], 'component': [], 'contrast': FIG['validation'].get('contrast', [])}
for n, v in prim.items():
    data['primitives'].append({'n': n, 't': v['type'], 'v': v['values']['Value'], 'css': dash(n)})
for n, v in sem.items():
    cn = code_name(n)
    data['semantic'].append({'n': n, 't': v['type'], 'light': v['values']['Light'], 'dark': v['values']['Dark'], 'rl': v['resolved']['Light'], 'rd': v['resolved']['Dark'],
        'note': (cloud_names[cn]['usage'] if cn else '') or v.get('note', ''), 'css': dash(n), 'code': ('--' + cn) if cn else None, 'scopes': v['scopes']})
for n, v in resp.items():
    data['responsive'].append({'n': n, 't': v['type'], 'r': v['resolved'], 'css': dash(n)})
for n, v in comp.items():
    data['component'].append({'n': n, 't': v['type'], 'alias': v['alias'], 'css': dash(n)})
data['cloud'] = {k: CLOUD[k] for k in ['spacing', 'radius', 'shadow', 'size', 'borderWidth']}
data['type'] = CLOUD['type']
data['colorCloud'] = CLOUD['color']['tokens']
open(os.path.join(ROOT, 'src/gen/tokens.json'), 'w').write(json.dumps(data, separators=(',', ':')))
for f in CLOUD['type']['fonts']: shutil.copy(os.path.join(ROOT, 'design-system/fonts', os.path.basename(f['file'])), os.path.join(ROOT, 'out', f['file']))
print('css', len(css), 'sem mapped', sum(1 for x in data['semantic'] if x['code']), '/', len(data['semantic']))
print([x['n'] for x in data['semantic'] if not x['code']][:60])
